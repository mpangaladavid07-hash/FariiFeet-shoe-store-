const dictionaries = { en, sw }

function resolve(dictionary, key) {
  return key.split('.').reduce((value, part) => {
    if (value && typeof value === 'object' && part in value) return value[part]
    return undefined
  }, dictionary)
}

/** Translate outside React (e.g. the WhatsApp message builders in store.js). */
export function translate(lang, key, vars) {
  const dictionary = dictionaries[lang] || dictionaries.en
  const template = resolve(dictionary, key) ?? resolve(dictionaries.en, key) ?? key
  if (typeof template !== 'string' || !vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined || vars[name] === null ? match : String(vars[name]),
  )
}

function readStoredLanguage() {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored && dictionaries[stored]) return stored
    const browserLanguage = (window.navigator.language || '').toLowerCase()
    if (browserLanguage.startsWith('sw')) return 'sw'
  } catch (error) {
    /* private mode / storage disabled — fall back to English */
  }
  return 'en'
}

const I18nContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(readStoredLanguage)

  useEffect(() => {
    document.documentElement.lang = lang
    try {
      window.localStorage.setItem(STORAGE_KEY, lang)
    } catch (error) {
      /* ignore unavailable storage */
    }
  }, [lang])

  const setLang = useCallback((next) => {
    if (dictionaries[next]) setLangState(next)
  }, [])

  const toggleLang = useCallback(() => {
    setLangState((current) => (current === 'en' ? 'sw' : 'en'))
  }, [])

  const t = useCallback((key, vars) => translate(lang, key, vars), [lang])

  const value = useMemo(
    () => ({ lang, setLang, toggleLang, t, isSwahili: lang === 'sw' }),
    [lang, setLang, toggleLang, t],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside <LanguageProvider>')
  return context
}

